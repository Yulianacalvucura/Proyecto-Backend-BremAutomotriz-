-- =====================================================================
-- BREM AUTOMOTRIZ - Base de datos PostgreSQL compartida (backend con 3 microservicios)
-- Motor: PostgreSQL 16
-- Basada en las entidades del proyecto Android (Room): Usuario, Cliente,
-- Vehiculo, OrdenTrabajo, LineaOt y EvidenciaOt.
--
-- Como ejecutarlo (con un usuario administrador, por ejemplo postgres):
--   CREATE DATABASE no puede ejecutarse dentro de un script ya conectado.
--   Antes de este script, desde la terminal:
--     psql -U postgres -c "CREATE DATABASE brem_automotriz;"
--   Luego, dentro de psql, conectarse a la base con:
--     \c brem_automotriz
--   Y ejecutar este archivo:
--     psql -U postgres -f database\postgres\brem_automotriz.sql
--   (o desde psql: \i database/postgres/brem_automotriz.sql)
--
-- Que microservicio usa que tablas:
--   ms-usuarios    -> usuarios
--   ms-clientes    -> clientes, vehiculos
--   ms-ordenes     -> ordenes_trabajo, lineas_ot, evidencias_ot
-- =====================================================================

-- CREATE DATABASE brem_automotriz;  -> se ejecuta fuera, con psql -c (ver arriba)
-- USE brem_automotriz;              -> se reemplaza por \c brem_automotriz en psql

-- ---------------------------------------------------------------------
-- 1) TABLAS
-- ---------------------------------------------------------------------

-- MICROSERVICIO USUARIOS
-- Seguridad: NUNCA se guarda la contrasena en texto plano (en la app
-- Android si se hacia). Aqui se guarda solo el HASH (BCrypt, 60 caracteres).
-- El ENUM de MySQL se reemplaza por VARCHAR + CHECK para que Hibernate
-- con EnumType.STRING pueda leer/escribir el valor sin conversiones.
CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100)    NOT NULL,
    email          VARCHAR(100)    NOT NULL,
    password_hash  VARCHAR(255)    NOT NULL,
    rol            VARCHAR(20)     NOT NULL,
    activo         BOOLEAN         NOT NULL DEFAULT TRUE,
    creado_en      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_rol    CHECK (rol IN ('ADMIN', 'JEFE')),
    CONSTRAINT ck_usuarios_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    CONSTRAINT ck_usuarios_email  CHECK (email LIKE '%_@_%._%')
);

-- MICROSERVICIO CLIENTES
CREATE TABLE clientes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(100)    NOT NULL,
    run       VARCHAR(12)     NULL,          -- en la app el RUN es opcional
    telefono  VARCHAR(20)     NULL,
    correo    VARCHAR(100)    NULL,
    CONSTRAINT uk_clientes_run UNIQUE (run), -- varios NULL permitidos
    CONSTRAINT ck_clientes_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) > 0)
);

CREATE TABLE vehiculos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patente     CHAR(6)           NOT NULL,
    marca       VARCHAR(50)       NOT NULL,
    modelo      VARCHAR(50)       NOT NULL,
    anio        SMALLINT          NOT NULL,
    vin         VARCHAR(17)       NULL,
    tipo        VARCHAR(30)       NULL,      -- Auto, Camioneta, etc.
    cliente_id  BIGINT            NOT NULL,
    CONSTRAINT uk_vehiculos_patente UNIQUE (patente),
    CONSTRAINT fk_vehiculos_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_vehiculos_anio_no_negativo CHECK (anio >= 0),
    CONSTRAINT ck_vehiculos_patente CHECK (patente ~ '^[A-Z0-9]{6}$'),
    CONSTRAINT ck_vehiculos_anio    CHECK (anio BETWEEN 1950 AND 2100)
);

-- MICROSERVICIO ORDENES
-- Cambio respecto a la app: ya NO se repiten patente ni nombre del cliente
-- dentro de la orden (eso duplicaba datos). Se obtienen con JOIN o con la
-- vista vista_ordenes.
CREATE TABLE ordenes_trabajo (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehiculo_id          BIGINT          NOT NULL,
    creado_por           BIGINT          NOT NULL,   -- usuario que creo la OT
    fecha_ingreso        TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_registro       TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    kilometraje          INTEGER         NOT NULL,
    observacion_ingreso  VARCHAR(500)    NOT NULL,
    observacion_entrega  VARCHAR(500)    NULL,
    estado               VARCHAR(20)     NOT NULL DEFAULT 'PENDIENTE',
    neto                 INTEGER         NOT NULL DEFAULT 0,
    iva                  INTEGER         NOT NULL DEFAULT 0,
    porcentaje_iva       DECIMAL(5,2)    NOT NULL DEFAULT 19.00,
    total                INTEGER         NOT NULL DEFAULT 0,
    CONSTRAINT fk_ot_vehiculo
        FOREIGN KEY (vehiculo_id) REFERENCES vehiculos (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_ot_usuario
        FOREIGN KEY (creado_por) REFERENCES usuarios (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_ot_estado CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'LISTO', 'ENTREGADO', 'ANULADA')),
    CONSTRAINT ck_ot_kilometraje CHECK (kilometraje >= 0 AND kilometraje <= 1999999),
    CONSTRAINT ck_ot_neto_no_negativo   CHECK (neto >= 0),
    CONSTRAINT ck_ot_iva_no_negativo    CHECK (iva >= 0),
    CONSTRAINT ck_ot_total_no_negativo  CHECK (total >= 0),
    CONSTRAINT ck_ot_total       CHECK (total = neto + iva),
    CONSTRAINT ck_ot_porcentaje_iva CHECK (porcentaje_iva BETWEEN 0.00 AND 100.00)
);

-- Historial de cambios de estado de cada orden de trabajo.
-- estado_anterior admite NULL (primera transicion), por eso el CHECK lo permite.
CREATE TABLE historial_estados (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ot_id            BIGINT       NOT NULL,
    estado_anterior  VARCHAR(20)  NULL,
    estado_nuevo     VARCHAR(20)  NOT NULL,
    fecha_cambio     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion      VARCHAR(500) NULL,
    CONSTRAINT fk_historial_ot
        FOREIGN KEY (ot_id) REFERENCES ordenes_trabajo (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT ck_historial_estado_anterior
        CHECK (estado_anterior IS NULL OR estado_anterior IN ('PENDIENTE', 'EN_PROCESO', 'LISTO', 'ENTREGADO', 'ANULADA')),
    CONSTRAINT ck_historial_estado_nuevo
        CHECK (estado_nuevo IN ('PENDIENTE', 'EN_PROCESO', 'LISTO', 'ENTREGADO', 'ANULADA'))
);

CREATE TABLE lineas_ot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ot_id        BIGINT       NOT NULL,
    tipo         VARCHAR(20)  NOT NULL,
    descripcion  VARCHAR(100) NOT NULL,
    costo        INTEGER      NOT NULL,                  -- costo interno
    factor       DECIMAL(3,2) NOT NULL DEFAULT 1.30,     -- recargo OMEX/REPUESTO
    cobrado      INTEGER      NOT NULL,                  -- lo que se cobra al cliente
    CONSTRAINT fk_lineas_ot
        FOREIGN KEY (ot_id) REFERENCES ordenes_trabajo (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT ck_lineas_tipo CHECK (tipo IN ('OM', 'OMEX', 'REPUESTO', 'INSUMO')),
    CONSTRAINT ck_lineas_costo  CHECK (costo > 0),
    CONSTRAINT ck_lineas_costo_no_negativo  CHECK (costo >= 0),
    CONSTRAINT ck_lineas_cobrado_no_negativo CHECK (cobrado >= 0),
    CONSTRAINT ck_lineas_factor CHECK (factor >= 1.00),
    CONSTRAINT ck_lineas_desc   CHECK (CHAR_LENGTH(TRIM(descripcion)) > 0)
);

-- Fotos: la base de datos guarda solo la RUTA o URL del archivo,
-- la imagen en si se guarda en disco o en un servicio de archivos.
CREATE TABLE evidencias_ot (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ot_id   BIGINT       NOT NULL,
    tipo    VARCHAR(20)  NOT NULL DEFAULT 'VEHICULO',
    ruta    VARCHAR(255) NOT NULL,
    fecha   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_evidencias_ot
        FOREIGN KEY (ot_id) REFERENCES ordenes_trabajo (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT ck_evidencias_tipo CHECK (tipo IN ('VEHICULO', 'NIVEL', 'DOCUMENTO'))
);

-- Indices (en MySQL iban como KEY dentro del CREATE TABLE)
CREATE INDEX idx_vehiculos_cliente ON vehiculos (cliente_id);
CREATE INDEX idx_ot_vehiculo       ON ordenes_trabajo (vehiculo_id);
CREATE INDEX idx_ot_creado_por     ON ordenes_trabajo (creado_por);
CREATE INDEX idx_ot_estado         ON ordenes_trabajo (estado);
CREATE INDEX idx_historial_ot      ON historial_estados (ot_id);
CREATE INDEX idx_lineas_ot         ON lineas_ot (ot_id);
CREATE INDEX idx_evidencias_ot     ON evidencias_ot (ot_id);

-- ---------------------------------------------------------------------
-- 2) VISTA para la busqueda (patente, cliente o N° de OT)
--    Reemplaza las columnas patente y nombreCliente que estaban repetidas.
--    No lleva SQL SECURITY DEFINER: usa los permisos de quien la consulta.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW vista_ordenes AS
SELECT
    o.id            AS ot_id,
    v.patente       AS patente,
    c.nombre        AS nombre_cliente,
    o.estado        AS estado,
    o.fecha_ingreso AS fecha_ingreso,
    o.total         AS total,
    o.vehiculo_id   AS vehiculo_id
FROM ordenes_trabajo o
JOIN vehiculos v ON v.id = o.vehiculo_id
JOIN clientes  c ON c.id = v.cliente_id;

