-- =====================================================================
-- BREM AUTOMOTRIZ - Roles PostgreSQL con minimo privilegio
-- Motor: PostgreSQL 16
-- Equivalente a los GRANT de database/mysql/brem_automotriz.sql y de
-- db/usuario_taller.sql, pero SOLO para los 2 roles que usa la app:
--   brem_usuarios_svc -> usuarios
--   brem_taller_svc   -> clientes, vehiculos, ordenes_trabajo, lineas_ot,
--                        evidencias_ot, historial_estados, vista_ordenes
--
-- Como ejecutarlo (las contrasenas NO se guardan en este archivo):
--   psql -U postgres -d brem_automotriz -v usuarios_pass='...' -v taller_pass='...' -f db\postgres\usuarios_servicio.sql
-- En PowerShell, si la contrasena tiene caracteres especiales, usar
-- comillas dobles: -v usuarios_pass="..."
-- Ejecutar como el propietario/administrador de la base (en AWS RDS, el
-- usuario maestro). Los roles son objetos del cluster, no de una base.
-- =====================================================================

\set ON_ERROR_STOP on

-- Evita crear roles con contrasena vacia si se olvida alguna variable.
\if :{?usuarios_pass}
\else
  \echo ERROR: falta usuarios_pass (-v usuarios_pass='...')
  \quit
\endif

\if :{?taller_pass}
\else
  \echo ERROR: falta taller_pass (-v taller_pass='...')
  \quit
\endif

-- ---------------------------------------------------------------------
-- 1) ROLES (LOGIN para que los servicios puedan conectarse)
--    :'variable' se interpola como literal SQL; psql escapa las comillas.
-- ---------------------------------------------------------------------
CREATE ROLE brem_usuarios_svc LOGIN PASSWORD :'usuarios_pass';
CREATE ROLE brem_taller_svc   LOGIN PASSWORD :'taller_pass';

-- Si los roles ya existen, este script falla aqui. En ese caso, comentar
-- los CREATE ROLE anteriores y usar (con las mismas variables):
-- ALTER ROLE brem_usuarios_svc WITH LOGIN PASSWORD :'usuarios_pass';
-- ALTER ROLE brem_taller_svc   WITH LOGIN PASSWORD :'taller_pass';

-- ---------------------------------------------------------------------
-- 2) SCHEMA public
--    PostgreSQL 16 ya no concede CREATE a PUBLIC en public, pero si concede
--    USAGE. Lo revocamos para que cada rol solo vea lo que se le otorga
--    explicitamente abajo. Por eso hace falta el GRANT USAGE posterior.
--    Las tablas no tienen privilegios para PUBLIC por defecto, asi que no
--    hace falta un REVOKE adicional sobre ellas.
-- ---------------------------------------------------------------------
REVOKE ALL ON SCHEMA public FROM PUBLIC;

GRANT USAGE ON SCHEMA public TO brem_usuarios_svc;
GRANT USAGE ON SCHEMA public TO brem_taller_svc;

-- ---------------------------------------------------------------------
-- 3) PERMISOS POR TABLA (minimo privilegio)
-- ---------------------------------------------------------------------

-- auth-usuarios-service: sin DELETE (los usuarios se desactivan con activo = 0)
GRANT SELECT, INSERT, UPDATE ON TABLE usuarios TO brem_usuarios_svc;

-- taller-service: Une los permisos que en MySQL tenian brem_clientes_svc
-- y brem_ordenes_svc. Las ordenes no se borran (se anulan); solo las
-- lineas se pueden eliminar; evidencias e historial son solo lectura + INSERT.
GRANT SELECT, INSERT, UPDATE ON TABLE clientes, vehiculos, ordenes_trabajo TO brem_taller_svc;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE lineas_ot TO brem_taller_svc;
GRANT SELECT, INSERT ON TABLE evidencias_ot, historial_estados TO brem_taller_svc;
GRANT SELECT ON TABLE vista_ordenes TO brem_taller_svc;

-- ---------------------------------------------------------------------
-- 4) SECUENCIAS: NO hace falta ningun GRANT USAGE ON SEQUENCE.
--    Los IDs del script database/postgres/brem_automotriz.sql son
--    BIGINT GENERATED BY DEFAULT AS IDENTITY, no serial. PostgreSQL guarda
--    la secuencia como dependencia interna de la columna: con solo el
--    INSERT sobre la tabla, el motor genera el valor (al contrario que con
--    serial, donde si hacia falta GRANT USAGE sobre la secuencia).
--    unicamente si se llamara directamente a nextval()/currval()/setval()
--    sobre esa secuencia haria falta conceder privilegios sobre ella; la
--    aplicacion no lo hace (usa los valores generados por el INSERT).
-- ---------------------------------------------------------------------
